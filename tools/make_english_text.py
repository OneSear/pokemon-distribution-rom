#!/usr/bin/env python3
"""Generate the English text for the language switch from pret/pokered.

pokered-fr is a translation of pret/pokered, and the two still share their text
files one for one: same file names, and (almost) the same labels. So instead of
translating anything by hand, this copies pret's English text into text_en/,
with every label renamed to <label>_EN so it can live next to the French one,
and writes text_en.asm: English sections grouped exactly like the French ones
in text.asm, plus the table TX_FAR uses to swap a French text for its English
twin at run time (see DistFarTextLookup). It also copies the English Pokémon
and move name tables; text.asm puts the move names next to the French ones.

The output is committed, so building the ROM does not need pret/pokered. Re-run
this only to refresh the English text:

    git clone --depth 1 https://github.com/pret/pokered /path/to/pokered
    python3 tools/make_english_text.py /path/to/pokered
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
OUT = os.path.join(REPO, "text_en")

LABEL_DEF = re.compile(r"^([A-Za-z_][A-Za-z0-9_]*)(::?)", re.M)

# English lines that only fit the 18-tile text box because pret's font has
# single-tile contractions ('d 'l 'm 'r 't 'v). The French font has none of
# those glyphs, so here they take two tiles and these two lines would run over.
FIXES = {
    "data/text/text_2.asm": [
        ('text "If you\'re studying "', 'text "If you\'re studying"'),
    ],
    "data/text/text_5.asm": [
        ('text "You can\'t use items"\n\tline "here."',
         'text "You can\'t use"\n\tline "items here."'),
    ],
}


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


def labels(text):
    return [m.group(1) for m in LABEL_DEF.finditer(text)]


def french_sections():
    """[(section name, [included text files])] in text.asm order, for the
    "Text N" sections only (text.asm also holds the move names)."""
    sections = []
    for line in read(os.path.join(REPO, "text.asm")).splitlines():
        m = re.match(r'SECTION "([^"]+)"', line)
        if m:
            sections.append((m.group(1), []))
        m = re.match(r'INCLUDE "([^"]+)"', line)
        if m:
            sections[-1][1].append(m.group(1))
    return [s for s in sections if s[0].startswith("Text ")]


def main(pret):
    sections = french_sections()
    files = [f for _, fs in sections for f in fs]

    english = {f: read(os.path.join(pret, f)) for f in files}
    # Name tables too. GetMonName and GetName pick these in English mode.
    for f in ("data/pokemon/names.asm", "data/moves/names.asm"):
        english[f] = read(os.path.join(pret, f))
    for f, fixes in FIXES.items():
        for old, new in fixes:
            assert old in english[f], (f, old)
            english[f] = english[f].replace(old, new)

    # Every label any English file defines gets the suffix, and so does every
    # reference to one from inside the English files (a text_far between two
    # texts, say). References to anything else -- WRAM, engine labels -- stay.
    renamed = {l for text in english.values() for l in labels(text)}
    pattern = re.compile(r"(?<![\w.])(" + "|".join(
        sorted(map(re.escape, renamed), key=len, reverse=True)) + r")(?!\w)")
    header = "; Generated by tools/make_english_text.py from pret/pokered. Do not edit.\n\n"
    for f, text in english.items():
        write(os.path.join(OUT, f), header + pattern.sub(r"\1_EN", text))

    out = [header.rstrip("\n"), ""]
    for i, (name, fs) in enumerate(sections, 1):
        out.append(f'SECTION "English Text {i}", ROMX')
        out.append("")
        out += [f'INCLUDE "text_en/{f}"' for f in fs]
        out += ["", ""]

    out.append('SECTION "English Text Lookup", ROMX')
    out.append("")
    out.append('INCLUDE "text_en/data/pokemon/names.asm"')
    out.append('INCLUDE "engine/menus/distribution_text_lookup.asm"')
    out.append("")
    out.append("; One row per French text section: its bank, then its own table.")
    out.append("DistFarTextIndex:")
    for i, (name, fs) in enumerate(sections, 1):
        out.append(f'\tdb BANK("{name}")')
        out.append(f"\tdw DistFarText{i}")
    out.append("\tdb 0 ; end")
    out.append("")
    out.append("; French address, then the English address and bank (the same")
    out.append("; layout as a text_far). Each table ends with a zero address,")
    out.append("; which no ROMX text can have.")
    missing = []
    for i, (name, fs) in enumerate(sections, 1):
        out.append(f"DistFarText{i}: ; {name}")
        for f in fs:
            for l in labels(read(os.path.join(REPO, f))):
                if l in renamed:
                    out.append(f"\tdw {l}\n\tdab {l}_EN")
                else:
                    missing.append(l)
        out.append("\tdw 0")
    write(os.path.join(REPO, "text_en.asm"), "\n".join(out) + "\n")

    print(f"{len(renamed)} English labels; French-only, left untranslated: "
          + (", ".join(missing) or "none"))


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
